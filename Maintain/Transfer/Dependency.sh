echo "  Auto-discovered : from Land/Dependency/**/.gitmodules"
echo "  Manual extras   : REPOS_EXTRA (forks + related)"
echo "=================================================================="
echo ""

if [[ ${#UNIQUE_REPOS[@]} -eq 0 ]]; then
	echo "ERROR: No repos discovered." >&2
	exit 1
fi

# ── Transfer function ─────────────────────────────────────────────────────────
transfer_repo() {
	local REPO="$1"
	local FULL="${SOURCE_ORG}/${REPO}"

	if ! gh repo view "${FULL}" &> /dev/null 2>&1; then
		printf "  [SKIP]  %-60s not found / no access\n" "${REPO}"
		SKIPPED+=("${REPO}")
		return
	fi

	if gh repo view "${DEST_ORG}/${REPO}" &> /dev/null 2>&1; then
		printf "  [SKIP]  %-60s already in %s\n" "${REPO}" "${DEST_ORG}"
		SKIPPED+=("${REPO}")
		return
	fi

	if [[ "${DRY_RUN}" == "1" ]]; then
		printf "  [DRY]   %-60s would transfer\n" "${REPO}"
		SUCCESS+=("${REPO}")
		return
	fi

	printf "  [XFER]  %-60s ... " "${REPO}"
	if gh api \
		--method POST \
		"repos/${FULL}/transfer" \
		-f "new_owner=${DEST_ORG}" \
		--silent 2> /dev/null; then
		echo "OK"
		SUCCESS+=("${REPO}")
	else
		echo "FAILED"
		FAILED+=("${REPO}")
	fi

	sleep 0.5
}

# ── Transfer ──────────────────────────────────────────────────────────────────
echo "── Transferring ${#UNIQUE_REPOS[@]} repos ───────────────────────────────────────"
for r in "${UNIQUE_REPOS[@]}"; do
	transfer_repo "${r}"
done

# ── Summary ───────────────────────────────────────────────────────────────────
echo ""
echo "=================================================================="
echo "  Summary"
echo "=================================================================="
echo "  Transferred : ${#SUCCESS[@]}"
echo "  Skipped     : ${#SKIPPED[@]}"
echo "  Failed      : ${#FAILED[@]}"

if [[ ${#FAILED[@]} -gt 0 ]]; then
	echo ""
	echo "  Failed — retry individually:"
	for r in "${FAILED[@]}"; do
		echo "    gh api --method POST repos/${SOURCE_ORG}/${r}/transfer -f new_owner=${DEST_ORG}"
	done
	exit 1
fi
