#!/usr/bin/env bash
# Maintain/Transfer/Dependency.sh
#
# 1. Dynamically discovers all repos under Land/Dependency/**/.gitmodules
# 2. Also transfers a manually-curated REPOS_EXTRA list (forks + related repos
#    not referenced by any .gitmodules)
#
# Usage (run from Land/):
#   chmod +x Maintain/Transfer/Dependency.sh
#   DRY_RUN=1 ./Maintain/Transfer/Dependency.sh   # preview only
#   ./Maintain/Transfer/Dependency.sh             # real run

set -euo pipefail

# ── Configuration ─────────────────────────────────────────────────────────────
SOURCE_ORG="CodeEditorLand"
DEST_ORG="DependencyCodeEditorLand"
DRY_RUN="${DRY_RUN:-0}"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LAND_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
DEPENDENCY_ROOT="${LAND_ROOT}/Dependency"

FAILED=()
SKIPPED=()
SUCCESS=()

# ── Sanity checks ─────────────────────────────────────────────────────────────
if ! command -v gh &> /dev/null; then
	echo "ERROR: gh CLI not found. Install: https://cli.github.com/" >&2
	exit 1
fi

if ! gh auth status &> /dev/null; then
	echo "ERROR: Not authenticated. Run: gh auth login" >&2
	exit 1
fi

if [[ ! -d "${DEPENDENCY_ROOT}" ]]; then
	echo "ERROR: Dependency directory not found: ${DEPENDENCY_ROOT}" >&2
	echo "       Run: git submodule update --init --recursive -- Dependency" >&2
	exit 1
fi

# ── Manual extras: forks not referenced in any .gitmodules ────────────────────
# Generated by Maintain/List/Fork.sh on 2026-06-07, minus repos already
# covered by the dynamic .gitmodules scan below.
# Remove any line you want to KEEP in CodeEditorLand.
